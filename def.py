# ЗАДАНИЕ 8 (со звёздочкой). Декомпозиция хода
# Создай функцию process_turn(choice, health, money).
# Внутри:
#   если choice == "1" -> money + 30, вернуть (health, money)
#   если choice == "2" -> health + 20, вернуть (health, money)
#   иначе -> печатает "Не понял", вернуть (health, money)
# Вызови функцию с разными значениями и напечатай результат.

# Напиши код здесь:
def process_turn(choice, health, money):
    if choice == "1":
        money += 30
    elif choice == "2":
        health += 20
    else:
        print("Не понял")
    
    return health, money

# Вызываем функцию с разными значениями и печатаем результат
print(process_turn("1", 100, 50))   # choice="1": +30 к деньгам → (100, 80)
print(process_turn("2", 100, 50))   # choice="2": +20 к здоровью → (120, 50)
print(process_turn("3", 100, 50))   # choice="3": непонятно → печатает "Не понял", возвращает (100, 50)
